  CHECK((c[0].lemma == 1 && c[0].score == 175 && c[0].pos == Verb));
  CHECK((c[1].lemma == 4 && c[1].score == 95));   // tie at 95: lemma 4 before lemma 5
  CHECK((c[2].lemma == 5 && c[2].score == 95));
