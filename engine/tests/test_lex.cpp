std::string hex(const uint8_t* p, size_t n) {
  std::ostringstream o;
  for (size_t i = 0; i < n; ++i) o << std::hex << std::setw(2) << std::setfill('0') << static_cast<int>(p[i]) << (i + 1 < n ? " " : "");
  return o.str();
}

uint32_t rd32(const Bytes& b, size_t at) {
  return static_cast<uint32_t>(b[at]) | (static_cast<uint32_t>(b[at + 1]) << 8) | (static_cast<uint32_t>(b[at + 2]) << 16) |
         (static_cast<uint32_t>(b[at + 3]) << 24);
}

void writeSpecCheck() {
  std::ostringstream md;
  md << "# `.vpl` spec check (generated)\n\n"
     << "Generated by `VP_REGEN_LEX_FIXTURES=1 vp_tests -tc='lex: committed fixtures*'` from the reference encoder\n"
     << "`engine/tests/lex_fixture_writer.cpp` (DESIGN.md §5). The Python packer (`tools/build_library/pack.py`) should\n"
     << "reproduce these offsets for the same input; with the STRS convention below it can reproduce the bytes.\n\n"
     << "Header fields are packed in the order of §5: magic @0, major u16 @4, minor u16 @6, lang char[8] @8,\n"
     << "section_count u32 @16, file_size u64 @20 (unaligned), sha256 u8[32] @28 (of bytes [256, file_size)), zeros\n"
     << "to 256. Section table @256: 24-byte entries {char[4] tag, u32 reserved=0, u64 offset, u64 length}, in file\n"
     << "order. Each section starts 8-byte aligned (zero gap before it); `length` is unpadded; the file ends at the end\n"
     << "of the last section. STRS: a NUL at offset 0 (empty string; \"none\" fields such as emoji_off are 0), then\n"
     << "every distinct non-empty string sorted bytewise, each NUL-terminated. FEAT: every packed word used by ANAL or\n"
     << "GENX, ascending (feat_id = index). KEYS keys and REVX keywords sorted bytewise; ANAL grouped by key; GENX\n"
     << "sorted by feat_id inside each lemma; CAND sorted by score desc, lemma id asc, sense asc.\n";
  for (const Named& n : kFixtures) {
    std::vector<vp::lexfix::SectionInfo> layout;
    const Bytes b = vp::lexfix::build(n.make(), &layout);
    md << "\n## " << n.file << "\n\n"
       << "- file size: " << b.size() << " bytes\n"
       << "- SHA-256 of the whole file: `" << vp::sha256Hex(std::string_view(reinterpret_cast<const char*>(b.data()), b.size())) << "`\n"
       << "- header bytes 0..63: `" << hex(b.data(), 64) << "`\n\n"
       << "| tag | offset | length | first u32 (count) |\n|---|---|---|---|\n";
    for (const auto& s : layout)
      md << "| " << s.tag << " | " << s.offset << " | " << s.length << " | "
         << (s.tag == "NOTE" || s.tag == "STRS" ? std::string("-") : std::to_string(rd32(b, s.offset))) << " |\n";
  }
  std::ofstream(fixturePath("SPEC_CHECK.md"), std::ios::binary | std::ios::trunc) << md.str();
}

// Calls every query on a (possibly damaged) lexicon and reads every byte of every view it returns.
size_t exercise(const Lexicon& lx, const std::vector<std::string>& keys, const std::vector<std::string>& kws) {
  size_t sum = 0;
  auto touch = [&](std::string_view s) { for (char c : s) sum += static_cast<unsigned char>(c); };
  std::vector<Analysis> an;
  std::vector<std::string_view> pv;
  std::vector<vp::lex::Sense> ss;
  std::vector<std::pair<uint32_t, std::string_view>> cs;
  std::vector<Candidate> cd;
  touch(lx.lang()); touch(lx.notice());
  (void)lx.stats();
  for (const std::string& k : keys) lx.lookup(k, an);
  for (const Analysis& a : an) { touch(a.display); touch(lx.lemma(a.lemma).head); sum += lx.feature(a.feat); }
  lx.prefix("", 100000, pv);
  lx.prefix("am", 50, pv);
  for (std::string_view s : pv) touch(s);
  const uint32_t n = std::min<uint32_t>(lx.lemmaCount(), 4096) + 3;
  for (uint32_t id = 0; id < n; ++id) {
    const vp::lex::Lemma l = lx.lemma(id);
    touch(l.head); touch(l.key); touch(l.glossEn); touch(l.glossEs); touch(l.emoji); touch(l.principal);
    ss.clear(); lx.senses(id, ss);
    for (const auto& s : ss) { touch(s.glossEn); touch(s.glossEs); touch(s.keywords); }
    cs.clear(); lx.cells(id, cs);
    for (const auto& c : cs) {
      touch(c.second);
      std::string_view f;
      if (lx.generate(id, c.first, f)) touch(f);
    }
    std::string_view f;
    if (lx.generate(id, PK(Noun, Gen, Pl), f)) touch(f);
  }
  for (const std::string& k : kws) { cd.clear(); lx.reverse(k, cd); for (const auto& c : cd) sum += c.lemma + c.score; }
  for (uint32_t i = 0; i < 300; ++i) {
    bool found = false;
    sum += lx.featId(lx.feature(static_cast<uint16_t>(i)), found);
  }
  return sum;
}

